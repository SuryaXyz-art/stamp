// Generates typed artifacts the web app imports, so it runs with zero env vars:
//   contracts/abi/StampBox.json              plain ABI (for other tooling)
//   web/src/generated/stampBoxAbi.ts         `as const` ABI for viem/wagmi types
//   web/src/generated/deployments.ts         address + start block per chain from deployments/*.json
// Run after `forge build` and after every deployment: `pnpm abi`.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const artifact = join(root, "out", "StampBox.sol", "StampBox.json");
if (!existsSync(artifact)) {
  console.error("Missing build output. Run `forge build` first.");
  process.exit(1);
}

const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
const webGenerated = join(root, "..", "web", "src", "generated");
mkdirSync(join(root, "abi"), { recursive: true });
mkdirSync(webGenerated, { recursive: true });

writeFileSync(join(root, "abi", "StampBox.json"), JSON.stringify(abi, null, 2) + "\n");
writeFileSync(
  join(webGenerated, "stampBoxAbi.ts"),
  `// Generated by contracts/scripts/export-abi.mjs. Do not edit.\nexport const stampBoxAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);

const deploymentsDir = join(root, "deployments");
const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const file of readdirSync(deploymentsDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(deploymentsDir, file), "utf8"));
    deployments[d.chainId] = { address: d.address, startBlock: d.startBlock };
  }
}
writeFileSync(
  join(webGenerated, "deployments.ts"),
  `// Generated by contracts/scripts/export-abi.mjs from contracts/deployments/*.json. Do not edit.\n` +
    `export const deployments: Record<number, { address: \`0x\${string}\`; startBlock: number }> = ${JSON.stringify(deployments, null, 2)};\n`,
);

console.log(`ABI exported (${abi.length} entries); deployments for chains: ${Object.keys(deployments).join(", ") || "none"}`);
